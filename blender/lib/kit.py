"""
Procedural hard-surface modelling kit for Interstellar: Beyond Endurance.

Every asset in the game is generated by scripts that import this module and run inside Blender
(either the `blender` executable or the `bpy` Python module). Conventions:

* Blender space: X = starboard/right, Y = forward, Z = up, metres.
* Material names form a shared vocabulary that the runtime MaterialLibrary upgrades to full PBR.
* Custom object properties become glTF extras -> three.js userData:
    col      : "mesh" | "box" | "none"   collision generation hint
    interact : interaction type ("door", "seat", "hatch", "console", "switch", ...)
    iid      : interaction id string
* `uv_box` writes metre-scale box-projected UVs so tiling detail textures have a consistent texel density.
"""
