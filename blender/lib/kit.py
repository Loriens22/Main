def world_matrix(o):
    mw = o.matrix_basis.copy()
    p = o.parent
    while p is not None:
        mw = p.matrix_basis @ mw
        p = p.parent
    return mw


def merge(objs, name, par=None, keep_space=None, **props):
    """Merge mesh objects (modifiers applied) into one object in the space of `keep_space` (an object) or world."""
    objs = [o for o in objs if o is not None and o.type == "MESH"]
    if not objs:
        return None
    ref = world_matrix(keep_space).inverted() if keep_space is not None else Matrix.Identity(4)
    bm = bmesh.new()
    mats = []
    for o in objs:
        bake(o)
        me = o.data
        m = ref @ world_matrix(o)
        tmp = me.copy()
        tmp.transform(m)
        before = len(bm.faces)
        bm.from_mesh(tmp)
        bm.faces.ensure_lookup_table()
        if m.determinant() < 0:
            bmesh.ops.reverse_faces(bm, faces=bm.faces[before:])
        remap = []
        for sm in me.materials:
            if sm is None:
                sm = M("paint_white_aero")
            if sm.name not in [x.name for x in mats]:
                mats.append(sm)
            remap.append([x.name for x in mats].index(sm.name))
        for f in bm.faces[before:]:
            if remap:
                f.material_index = remap[min(f.material_index, len(remap) - 1)]
            else:
                f.material_index = 0
        bpy.data.meshes.remove(tmp)
    for o in objs:
        bpy.data.objects.remove(o, do_unlink=True)
    me = bpy.data.meshes.new(name)
    bm.to_mesh(me)
    bm.free()
    out = bpy.data.objects.new(name, me)
    link(out)
    for mm in mats:
        me.materials.append(mm)
    if par is not None:
        out.parent = par
    set_props(out, **props)
    return out


def uv_box(o, scale=1.0):
    """Metre-scale box projection UVs (object space)."""
    me = o.data
    if not me.uv_layers:
        me.uv_layers.new(name="UVMap")
    uv = me.uv_layers.active.data
    for p in me.polygons:
        n = p.normal
        ax = max(range(3), key=lambda k: abs(n[k]))
        for li in p.loop_indices:
            co = me.vertices[me.loops[li].vertex_index].co
            if ax == 0:
                u, v = co.y * (1 if n.x > 0 else -1), co.z
            elif ax == 1:
                u, v = co.x * (-1 if n.y > 0 else 1), co.z
            else:
                u, v = co.x, co.y * (1 if n.z > 0 else -1)
            uv[li].uv = (u * scale, v * scale)
    return o


def origin_to(o, point):
    """Move object origin to `point` (in object's parent space) keeping geometry fixed."""
    point = V(point)
    delta = point - o.location
    o.data.transform(Matrix.Translation(-delta))
    o.location = point
    return o


def finish(o, angle=35, uv=True):
    bake(o)
    smooth(o, angle)
    if uv:
        uv_box(o)
    return o


def finish_all(root, angle=35):
    for o in all_children(root, include_self=True):
        if o.type == "MESH":
            finish(o, angle)


def all_children(o, include_self=False):
    out = [o] if include_self else []
    for c in o.children:
        out.extend(all_children(c, True))
    return out


def instance_copy(o, name, loc=None, rot=None, par=None, linked=True):
    c = o.copy()
    if not linked and o.data is not None:
        c.data = o.data.copy()
    c.name = name
    link(c)
    if par is not None:
        c.parent = par
    if loc is not None:
        c.location = loc
    if rot is not None:
        c.rotation_euler = rot
    return c


def rivets_along(name, pts2d, zfun, spacing=0.12, r=0.012, h=0.008, m="rivet_steel", closed=True):
    """Small rivet heads along a 2D path, heights given by zfun(x,y)."""
    bm = bmesh.new()
    pts = list(pts2d) + ([pts2d[0]] if closed else [])
    for i in range(len(pts) - 1):
        a = V(pts[i]); b = V(pts[i + 1])
        L = (b - a).length
        k = max(1, int(L / spacing))
        for s in range(k):
            p = a.lerp(b, (s + 0.5) / k)
            z = zfun(p.x, p.y)
            res = bmesh.ops.create_cone(bm, cap_ends=True, segments=6, radius1=r, radius2=r * 0.7, depth=h)
            for v in res["verts"]:
                v.co += V((p.x, p.y, z + h * 0.5))
    return from_bmesh(name, bm, (m,))


