def add_bevel(o, width, segs=2, angle=40):
    mod = o.modifiers.new("bevel", "BEVEL")
    mod.width = width
    mod.segments = segs
    mod.limit_method = "ANGLE"
    mod.angle_limit = math.radians(angle)
    mod.miter_outer = "MITER_ARC"
    try:
        mod.use_clamp_overlap = True
    except Exception:
        pass
    return mod


def add_solidify(o, t, offset=-1.0):
    mod = o.modifiers.new("solid", "SOLIDIFY")
    mod.thickness = t
    mod.offset = offset
    mod.use_even_offset = True
    return mod


def bake(o):
    """Apply all modifiers without operator context."""
    if not o.modifiers:
        return o
    dg = bpy.context.evaluated_depsgraph_get()
    dg.update()
    eo = o.evaluated_get(dg)
    me = bpy.data.meshes.new_from_object(eo, preserve_all_data_layers=True, depsgraph=dg)
    old = o.data
    o.modifiers.clear()
    o.data = me
    if old.users == 0:
        bpy.data.meshes.remove(old)
    return o


def boolean(o, cutters, op="DIFFERENCE", delete=True, solver="EXACT"):
    if not isinstance(cutters, (list, tuple)):
        cutters = [cutters]
    bake(o)
    for c in cutters:
        bake(c)
        mod = o.modifiers.new("bool", "BOOLEAN")
        mod.operation = op
        mod.object = c
        try:
            mod.solver = solver
        except Exception:
            pass
        bake(o)
        if delete:
            bpy.data.objects.remove(c, do_unlink=True)
    return o


def smooth(o, angle=35):
    me = o.data
    try:
        me.shade_smooth()
    except Exception:
        for p in me.polygons:
            p.use_smooth = True
    try:
        me.set_sharp_from_angle(angle=math.radians(angle))
    except Exception:
        pass
    return o


def flat(o):
    for p in o.data.polygons:
        p.use_smooth = False
    return o


def groove(o, planes, width=0.012, depth=0.008, seam_mat="hull_seam", region=None):
    """Cut real panel-line grooves: bisect the mesh with planes, bevel the cut edges, push the bevel faces in.
    planes: list of (point, normal). region: optional fn(Vector)->bool limiting which cut edges get grooved."""
    bake(o)
    me = o.data
    if seam_mat not in [m.name for m in me.materials]:
        me.materials.append(M(seam_mat))
    seam_idx = [m.name for m in me.materials].index(seam_mat)
    bm = bmesh.new()
    bm.from_mesh(me)
    cut_edges = set()
    for co, no in planes:
        geom = bm.verts[:] + bm.edges[:] + bm.faces[:]
        res = bmesh.ops.bisect_plane(bm, geom=geom, dist=1e-4, plane_co=V(co), plane_no=V(no))
        for e in res["geom_cut"]:
            if isinstance(e, bmesh.types.BMEdge):
                cut_edges.add(e)
    edges = [e for e in cut_edges if e.is_valid and len(e.link_faces) == 2]
    if region is not None:
        edges = [e for e in edges if region((e.verts[0].co + e.verts[1].co) * 0.5)]
    # only groove edges between nearly coplanar faces (flat-ish skin), not across hard corners
    edges = [e for e in edges if e.link_faces[0].normal.dot(e.link_faces[1].normal) > 0.85]
    if edges:
        res = bmesh.ops.bevel(bm, geom=edges, offset=width, offset_type="WIDTH", segments=2, profile=0.5,
                              affect="EDGES", clamp_overlap=True)
        faces = set(res["faces"])
        moved = set()
        for f in faces:
            f.material_index = seam_idx
        # push the middle verts of each groove inward
        for f in faces:
            for v in f.verts:
                if v in moved:
                    continue
                # a groove centre vertex is only linked to groove faces
                if all(lf in faces for lf in v.link_faces):
                    nrm = V((0, 0, 0))
                    for lf in v.link_faces:
                        nrm += lf.normal
                    if nrm.length > 0:
                        v.co -= nrm.normalized() * depth
                    moved.add(v)
    bm.to_mesh(me)
    bm.free()
    me.update()
    return o


def triangulate_ngons(o):
    bm = bmesh.new()
    bm.from_mesh(o.data)
    ngons = [f for f in bm.faces if len(f.verts) > 4]
    if ngons:
        bmesh.ops.triangulate(bm, faces=ngons)
    bm.to_mesh(o.data)
    bm.free()


