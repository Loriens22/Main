def _obj(name, me, mats=()):
    o = bpy.data.objects.new(name, me)
    link(o)
    for m in mats:
        if isinstance(m, str):
            m = M(m)
        me.materials.append(m)
    return o


def from_bmesh(name, bm, mats=("paint_white_aero",), loc=None, rot=None, par=None):
    me = bpy.data.meshes.new(name)
    bm.normal_update()
    bm.to_mesh(me)
    bm.free()
    o = _obj(name, me, mats)
    if par is not None:
        o.parent = par
    if loc is not None:
        o.location = loc
    if rot is not None:
        o.rotation_euler = rot
    return o


def box(name, size, loc=(0, 0, 0), rot=(0, 0, 0), m="paint_white_aero", bevel=0.0, segs=2, par=None, **props):
    bm = bmesh.new()
    bmesh.ops.create_cube(bm, size=1.0)
    for v in bm.verts:
        v.co = V((v.co.x * size[0], v.co.y * size[1], v.co.z * size[2]))
    o = from_bmesh(name, bm, (m,), loc, rot, par)
    if bevel > 0:
        add_bevel(o, bevel, segs)
    set_props(o, **props)
    return o


def cyl(name, r, depth, loc=(0, 0, 0), rot=(0, 0, 0), m="metal_gray", verts=32, bevel=0.0, segs=2, r2=None,
        cap=True, par=None, **props):
    """Cylinder along local Z (use rot to orient). r2 makes a cone/frustum."""
    bm = bmesh.new()
    bmesh.ops.create_cone(bm, cap_ends=cap, cap_tris=False, segments=verts, radius1=r,
                          radius2=r if r2 is None else r2, depth=depth)
    o = from_bmesh(name, bm, (m,), loc, rot, par)
    if bevel > 0:
        add_bevel(o, bevel, segs)
    set_props(o, **props)
    return o


def sphere(name, r, loc=(0, 0, 0), m="metal_gray", segs=24, rings=12, scale=(1, 1, 1), par=None, **props):
    bm = bmesh.new()
    bmesh.ops.create_uvsphere(bm, u_segments=segs, v_segments=rings, radius=r)
    for v in bm.verts:
        v.co = V((v.co.x * scale[0], v.co.y * scale[1], v.co.z * scale[2]))
    o = from_bmesh(name, bm, (m,), loc, None, par)
    set_props(o, **props)
    return o


def torus(name, R, r, loc=(0, 0, 0), rot=(0, 0, 0), m="metal_gray", seg=32, rseg=12, par=None):
    bm = bmesh.new()
    verts = []
    for i in range(seg):
        a = TAU * i / seg
        ring = []
        for j in range(rseg):
            b = TAU * j / rseg
            x = (R + r * math.cos(b)) * math.cos(a)
            y = (R + r * math.cos(b)) * math.sin(a)
            z = r * math.sin(b)
            ring.append(bm.verts.new((x, y, z)))
        verts.append(ring)
    for i in range(seg):
        for j in range(rseg):
            a = verts[i][j]; b = verts[(i + 1) % seg][j]
            c = verts[(i + 1) % seg][(j + 1) % rseg]; d = verts[i][(j + 1) % rseg]
            bm.faces.new((a, b, c, d))
    o = from_bmesh(name, bm, (m,), loc, rot, par)
    smooth(o, 60)
    return o


def prism(name, poly, z0, z1, m="paint_white_aero", loc=(0, 0, 0), rot=(0, 0, 0), bevel=0.0, segs=2, par=None,
          mats=None, **props):
    """Extrude a 2D polygon (CCW list of (x,y)) from z0 to z1."""
    bm = bmesh.new()
    n = len(poly)
    bot = [bm.verts.new((p[0], p[1], z0)) for p in poly]
    top = [bm.verts.new((p[0], p[1], z1)) for p in poly]
    bm.faces.new(list(reversed(bot)))
    bm.faces.new(top)
    for i in range(n):
        j = (i + 1) % n
        bm.faces.new((bot[i], bot[j], top[j], top[i]))
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    o = from_bmesh(name, bm, mats or (m,), loc, rot, par)
    if bevel > 0:
        add_bevel(o, bevel, segs)
    set_props(o, **props)
    return o


def prism_xz(name, poly, y0, y1, m="paint_white_aero", loc=(0, 0, 0), bevel=0.0, segs=2, par=None, **props):
    """Extrude a polygon given in the XZ plane along Y from y0 to y1."""
    o = prism(name, poly, 0, 1, m=m, par=par)
    me = o.data
    for v in me.vertices:
        x, zz, t = v.co.x, v.co.y, v.co.z
        v.co = V((x, y0 + (y1 - y0) * t, zz))
    me.update()
    _fix_normals(o)
    o.location = loc
    if bevel > 0:
        add_bevel(o, bevel, segs)
    set_props(o, **props)
    return o


def prism_yz(name, poly, x0, x1, m="paint_white_aero", loc=(0, 0, 0), bevel=0.0, segs=2, par=None, **props):
    """Extrude a polygon given in the YZ plane (as (y,z)) along X from x0 to x1."""
    o = prism(name, poly, 0, 1, m=m, par=par)
    me = o.data
    for v in me.vertices:
        yy, zz, t = v.co.x, v.co.y, v.co.z
        v.co = V((x0 + (x1 - x0) * t, yy, zz))
    me.update()
    _fix_normals(o)
    o.location = loc
    if bevel > 0:
        add_bevel(o, bevel, segs)
    set_props(o, **props)
    return o


def _fix_normals(o):
    bm = bmesh.new()
    bm.from_mesh(o.data)
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    bm.to_mesh(o.data)
    bm.free()


def loft(name, sections, m="paint_white_aero", closed=True, caps=True, par=None, mats=None, face_mats=None, **props):
    """Skin a list of sections (each a list of 3D points, equal counts).
    face_mats: optional fn(section_index, edge_index) -> material slot index."""
    bm = bmesh.new()
    rings = [[bm.verts.new(p) for p in sec] for sec in sections]
    n = len(sections[0])
    for s in range(len(rings) - 1):
        a, b = rings[s], rings[s + 1]
        rng = range(n) if closed else range(n - 1)
        for i in rng:
            j = (i + 1) % n
            try:
                f = bm.faces.new((a[i], a[j], b[j], b[i]))
                if face_mats:
                    f.material_index = face_mats(s, i)
            except ValueError:
                pass
    if caps and closed:
        try:
            bm.faces.new(list(reversed(rings[0])))
        except ValueError:
            pass
        try:
            bm.faces.new(rings[-1])
        except ValueError:
            pass
    bmesh.ops.remove_doubles(bm, verts=bm.verts, dist=1e-5)
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    o = from_bmesh(name, bm, mats or (m,), par=par)
    set_props(o, **props)
    return o


def tube(name, pts, r, m="pipe_blue", seg=10, par=None, closed=False):
    """Sweep a circle along a polyline (pipes, cables, handrails)."""
    bm = bmesh.new()
    pts = [V(p) for p in pts]
    rings = []
    for i, p in enumerate(pts):
        if i == 0:
            t = (pts[1] - pts[0]).normalized()
        elif i == len(pts) - 1:
            t = (pts[-1] - pts[-2]).normalized()
        else:
            t = ((pts[i + 1] - pts[i]).normalized() + (pts[i] - pts[i - 1]).normalized()).normalized()
        up = V((0, 0, 1)) if abs(t.z) < 0.9 else V((1, 0, 0))
        nx = t.cross(up).normalized()
        ny = nx.cross(t).normalized()
        ring = []
        for k in range(seg):
            a = TAU * k / seg
            ring.append(bm.verts.new(p + (nx * math.cos(a) + ny * math.sin(a)) * r))
        rings.append(ring)
    for i in range(len(rings) - 1):
        for k in range(seg):
            a = rings[i][k]; b = rings[i][(k + 1) % seg]
            c = rings[i + 1][(k + 1) % seg]; d = rings[i + 1][k]
            bm.faces.new((a, b, c, d))
    if not closed:
        bm.faces.new(list(reversed(rings[0])))
        bm.faces.new(rings[-1])
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    o = from_bmesh(name, bm, (m,), par=par)
    smooth(o, 70)
    return o


def lathe(name, profile, m="metal_gray", seg=32, loc=(0, 0, 0), rot=(0, 0, 0), par=None, **props):
    """Revolve a profile [(r, z), ...] around local Z."""
    bm = bmesh.new()
    rings = []
    for k in range(seg):
        a = TAU * k / seg
        ca, sa = math.cos(a), math.sin(a)
        rings.append([bm.verts.new((r * ca, r * sa, z)) for (r, z) in profile])
    n = len(profile)
    for k in range(seg):
        A, B = rings[k], rings[(k + 1) % seg]
        for i in range(n - 1):
            try:
                bm.faces.new((A[i], B[i], B[i + 1], A[i + 1]))
            except ValueError:
                pass
    bmesh.ops.remove_doubles(bm, verts=bm.verts, dist=1e-6)
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    o = from_bmesh(name, bm, (m,), loc, rot, par)
    smooth(o, 40)
    set_props(o, **props)
    return o


