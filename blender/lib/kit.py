def poly_area(p):
    a = 0.0
    for i in range(len(p)):
        x0, y0 = p[i]; x1, y1 = p[(i + 1) % len(p)]
        a += x0 * y1 - x1 * y0
    return a * 0.5


def ccw(p):
    return p if poly_area(p) > 0 else list(reversed(p))


def offset_poly(p, d):
    """Miter offset of a CCW polygon; d>0 grows outward."""
    p = ccw(p)
    n = len(p)
    out = []
    for i in range(n):
        x0, y0 = p[i - 1]; x1, y1 = p[i]; x2, y2 = p[(i + 1) % n]
        e0 = V((x1 - x0, y1 - y0)).normalized(); e1 = V((x2 - x1, y2 - y1)).normalized()
        n0 = V((e0.y, -e0.x)); n1 = V((e1.y, -e1.x))
        bis = (n0 + n1)
        if bis.length < 1e-6:
            bis = n0
        bis.normalize()
        cosh = max(0.25, bis.dot(n0))
        out.append((x1 + bis.x * d / cosh, y1 + bis.y * d / cosh))
    return out


def round_poly(p, r, segs=4):
    """Round the corners of a polygon with radius r (clamped per corner)."""
    p = ccw(p)
    n = len(p)
    out = []
    for i in range(n):
        P0 = V(p[i - 1]); P1 = V(p[i]); P2 = V(p[(i + 1) % n])
        a = (P0 - P1); b = (P2 - P1)
        la, lb = a.length, b.length
        a.normalize(); b.normalize()
        ang = math.acos(max(-1, min(1, a.dot(b))))
        if ang < 1e-3 or ang > math.pi - 1e-3:
            out.append(tuple(P1)); continue
        t = min(r / math.tan(ang / 2), la * 0.45, lb * 0.45)
        rr = t * math.tan(ang / 2)
        A = P1 + a * t; B = P1 + b * t
        bis = (a + b).normalized()
        C = P1 + bis * (rr / math.sin(ang / 2))
        sa = math.atan2(A.y - C.y, A.x - C.x); sb = math.atan2(B.y - C.y, B.x - C.x)
        da = sb - sa
        while da > math.pi: da -= TAU
        while da < -math.pi: da += TAU
        for k in range(segs + 1):
            ang_k = sa + da * k / segs
            out.append((C.x + rr * math.cos(ang_k), C.y + rr * math.sin(ang_k)))
    return out


def circle_pts(r, n=24, cx=0.0, cy=0.0, a0=0.0):
    return [(cx + r * math.cos(a0 + TAU * i / n), cy + r * math.sin(a0 + TAU * i / n)) for i in range(n)]


def mirror_x(pts):
    return [(-x, y) for (x, y) in pts]


def poly_ring(name, outer, inner, z0, z1, m="frame_black", par=None, bevel=0.0):
    """Extruded ring between two polygons with equal vertex counts (window frames, bezels)."""
    outer = ccw(outer); inner = ccw(inner)
    assert len(outer) == len(inner)
    bm = bmesh.new()
    n = len(outer)
    ob = [bm.verts.new((x, y, z0)) for x, y in outer]
    ot = [bm.verts.new((x, y, z1)) for x, y in outer]
    ib = [bm.verts.new((x, y, z0)) for x, y in inner]
    it = [bm.verts.new((x, y, z1)) for x, y in inner]
    for i in range(n):
        j = (i + 1) % n
        bm.faces.new((ot[i], ot[j], it[j], it[i]))   # top
        bm.faces.new((ob[j], ob[i], ib[i], ib[j]))   # bottom
        bm.faces.new((ob[i], ob[j], ot[j], ot[i]))   # outer wall
        bm.faces.new((ib[j], ib[i], it[i], it[j]))   # inner wall
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    o = from_bmesh(name, bm, (m,), par=par)
    if bevel > 0:
        add_bevel(o, bevel, 2)
    return o


