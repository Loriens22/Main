def mat(name, color=(0.8, 0.8, 0.8), metal=0.0, rough=0.5, emit=None, emit_strength=0.0, alpha=1.0,
        transmission=0.0, coat=0.0):
    if name in _MATS:
        return _MATS[name]
    m = bpy.data.materials.new(name)
    if hasattr(m, "use_nodes"):
        try:
            m.use_nodes = True
        except Exception:
            pass
    nt = m.node_tree
    bsdf = None
    for n in nt.nodes:
        if n.type == "BSDF_PRINCIPLED":
            bsdf = n
    if bsdf is None:
        nt.nodes.clear()
        bsdf = nt.nodes.new("ShaderNodeBsdfPrincipled")
        out = nt.nodes.new("ShaderNodeOutputMaterial")
        nt.links.new(bsdf.outputs[0], out.inputs[0])
    c = tuple(color) + (1.0,) if len(color) == 3 else tuple(color)
    bsdf.inputs["Base Color"].default_value = c
    bsdf.inputs["Metallic"].default_value = metal
    bsdf.inputs["Roughness"].default_value = rough
    if emit is not None:
        bsdf.inputs["Emission Color"].default_value = tuple(emit) + (1.0,)
        bsdf.inputs["Emission Strength"].default_value = emit_strength
    if alpha < 1.0:
        bsdf.inputs["Alpha"].default_value = alpha
        try:
            m.surface_render_method = "BLENDED"
        except Exception:
            pass
    if transmission > 0:
        bsdf.inputs["Transmission Weight"].default_value = transmission
    if coat > 0:
        bsdf.inputs["Coat Weight"].default_value = coat
    m.diffuse_color = c
    _MATS[name] = m
    return m


def M(name):
    """Fetch a material from the shared vocabulary (created on demand with sensible defaults)."""
    if name in _MATS:
        return _MATS[name]
    p = PALETTE.get(name)
    if p is None:
        return mat(name)
    return mat(name, **p)


