    s.data.angle = math.radians(3)
    s.rotation_euler = V(sun).to_track_quat("Z", "Y").to_euler()
    hidden = []
    for o in hide:
        if o:
            o.hide_render = True
            hidden.append(o)
    sc.render.filepath = os.path.abspath(path)
    bpy.ops.render.render(write_still=True)
    for o in hidden:
        o.hide_render = False
    print(f"[kit] preview -> {path}")


