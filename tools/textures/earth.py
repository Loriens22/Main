def lonlat_grid(w, h):
    lon = (np.arange(w) + 0.5) / w * 360.0 - 180.0
    lat = 90.0 - (np.arange(h) + 0.5) / h * 180.0
    return np.meshgrid(lon, lat)


def sphere_xyz(lon, lat):
    lo, la = np.radians(lon), np.radians(lat)
    return np.cos(la) * np.cos(lo), np.cos(la) * np.sin(lo), np.sin(la)


_PERM = np.random.RandomState(7).permutation(1024)


def _hash3(ix, iy, iz):
    return (_PERM[(_PERM[(_PERM[ix & 1023] + iy) & 1023] + iz) & 1023] / 1023.0).astype(np.float32)


def vnoise3(x, y, z):
    """Value noise on a 3D lattice (smooth, -> 0..1)."""
    ix, iy, iz = np.floor(x).astype(np.int64), np.floor(y).astype(np.int64), np.floor(z).astype(np.int64)
    fx, fy, fz = x - ix, y - iy, z - iz
    ux, uy, uz = fx * fx * (3 - 2 * fx), fy * fy * (3 - 2 * fy), fz * fz * (3 - 2 * fz)
    out = 0
    for dx in (0, 1):
        for dy in (0, 1):
            for dz in (0, 1):
                w = (ux if dx else 1 - ux) * (uy if dy else 1 - uy) * (uz if dz else 1 - uz)
                out = out + w * _hash3(ix + dx, iy + dy, iz + dz)
    return out


def fbm3(x, y, z, freq, octaves, gain=0.5, lac=2.03, seed=0.0, ridged=False):
    tot, amp, norm = 0.0, 1.0, 0.0
    for o in range(octaves):
        f = freq * lac ** o
        n = vnoise3(x * f + seed + o * 17.13, y * f + seed * 1.7 + o * 31.7, z * f - seed + o * 7.3)
        if ridged:
            n = 1.0 - np.abs(n * 2 - 1)
            n = n * n
        tot = tot + n * amp
        norm += amp
        amp *= gain
    return tot / norm


def rasterize(polys, w, h):
    img = Image.new("L", (w, h), 0)
    d = ImageDraw.Draw(img)
    for pts in polys:
        for shift in (-360, 0, 360):
            xy = [((lo + shift + 180.0) / 360.0 * w, (90.0 - la) / 180.0 * h) for lo, la in pts]
            d.polygon(xy, fill=255)
    return img


def smoothstep(a, b, x):
    t = np.clip((x - a) / (b - a), 0, 1)
    return t * t * (3 - 2 * t)


def dist_to_polyline(lon, lat, pts):
    """Angular-ish distance (deg) from every pixel to a polyline, longitude scaled by cos(lat)."""
    best = np.full(lon.shape, 1e9, dtype=np.float32)
    c = np.cos(np.radians(lat))
    for (x0, y0), (x1, y1) in zip(pts[:-1], pts[1:]):
        dx, dy = x1 - x0, y1 - y0
        L2 = dx * dx + dy * dy
        t = np.clip(((lon - x0) * dx + (lat - y0) * dy) / L2, 0, 1)
        px, py = x0 + t * dx, y0 + t * dy
        d = np.sqrt(((lon - px) * c) ** 2 + (lat - py) ** 2)
        best = np.minimum(best, d)
    return best


def main():
    t0 = time.time()
    W, H = 2048, 1024             # analysis resolution (upsampled for the albedo)
    lon, lat = lonlat_grid(W, H)
    X, Y, Z = sphere_xyz(lon, lat)
    # ---- land mask with fractal coastlines
    base = np.asarray(rasterize(LAND.values(), W, H).filter(ImageFilter.GaussianBlur(2.2)), dtype=np.float32) / 255.0
    water = np.asarray(rasterize(WATER.values(), W, H).filter(ImageFilter.GaussianBlur(2.0)), dtype=np.float32) / 255.0
    base = np.clip(base - water, 0, 1)
    coast_n = (fbm3(X, Y, Z, 6.0, 6, seed=3.1) - 0.5) * 0.5 + (fbm3(X, Y, Z, 26.0, 4, seed=3.7) - 0.5) * 0.42
    land_f = base + coast_n
    land = smoothstep(0.47, 0.53, land_f)
    print(f"  land mask {time.time() - t0:.1f}s")
    # ---- elevation (km): continental shelf, interior rise, mountain belts, ridged detail
    elev = (land_f - 0.5) * 2.2
    rid = fbm3(X, Y, Z, 4.0, 6, seed=9.3, ridged=True)
    hills = fbm3(X, Y, Z, 9.0, 5, seed=5.7)
    elev += land * (0.25 + 0.9 * rid * fbm3(X, Y, Z, 1.5, 3, seed=1.1) + 0.3 * (hills - 0.5))
    for pts, hgt, wid in RANGES:
        d = dist_to_polyline(lon, lat, pts)
        elev += land * hgt * np.exp(-(d / wid) ** 2) * (0.55 + 0.6 * rid)
    elev = np.where(land > 0.5, np.maximum(elev, 0.02), np.minimum(elev, -0.05))
    ocean_depth = np.clip(-elev, 0, 3)
    print(f"  relief {time.time() - t0:.1f}s")
    # ---- climate: temperature from latitude and height, moisture from latitude bands, coasts and noise
    alat = np.abs(lat)
    temp = 1.0 - alat / 70.0 - np.clip(elev, 0, 6) * 0.08
    band = np.exp(-((alat - 2) / 11) ** 2) * 1.0 + np.exp(-((alat - 52) / 12) ** 2) * 0.75 - np.exp(-((alat - 25) / 9) ** 2) * 0.85
    coast_dist = np.asarray(Image.fromarray((land * 255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(18)), dtype=np.float32) / 255.0
    moist = np.clip(0.52 + band * 0.5 - (coast_dist - 0.5) * 0.55 + (fbm3(X, Y, Z, 3.0, 5, seed=4.4) - 0.5) * 0.7, 0, 1)
    # blight: forests have shrunk, deserts spread (story)
    moist = np.clip(moist * 0.92 - 0.02, 0, 1)
    dust = fbm3(X, Y, Z, 2.2, 4, seed=8.8)
    # ---- palette
    def rgb(hexs):
        return np.array([int(hexs[i:i + 2], 16) for i in (1, 3, 5)], dtype=np.float32) / 255.0
    desert, steppe, grass, forest, jungle = rgb("#c7a97a"), rgb("#a79a6c"), rgb("#7c7d4c"), rgb("#4e5a35"), rgb("#3b4c2a")
    rock, tundra, snow = rgb("#857a6a"), rgb("#8a8370"), rgb("#eef1f3")
    c = np.zeros((H, W, 3), dtype=np.float32)
    land_col = desert * (1 - smoothstep(0.18, 0.38, moist))[..., None] + steppe * (smoothstep(0.18, 0.38, moist) * (1 - smoothstep(0.38, 0.55, moist)))[..., None] \
        + grass * (smoothstep(0.38, 0.55, moist) * (1 - smoothstep(0.55, 0.72, moist)))[..., None] \
        + forest * (smoothstep(0.55, 0.72, moist) * (1 - smoothstep(0.72, 0.9, moist)))[..., None] + jungle * smoothstep(0.72, 0.9, moist)[..., None]
    tund = smoothstep(0.24, 0.1, temp)[..., None]
    land_col = land_col * (1 - tund * 0.65) + tundra * tund * 0.65
    land_col = land_col * (1 - smoothstep(1.2, 3.5, elev)[..., None] * 0.6) + rock * smoothstep(1.2, 3.5, elev)[..., None] * 0.6
    land_col *= (0.85 + 0.3 * hills)[..., None]
    land_col = land_col * (1 - 0.25 * dust[..., None]) + rgb("#b49470") * 0.25 * dust[..., None]
    ice = np.clip(smoothstep(0.03, -0.1, temp) + smoothstep(4.3, 5.6, elev) * 0.85, 0, 1)
    ice = np.maximum(ice, smoothstep(72, 80, alat) * (lat < 0))
    land_col = land_col * (1 - ice[..., None]) + snow * ice[..., None]
    deep, shallow, mid = rgb("#0b2440"), rgb("#2e6f7c"), rgb("#123552")
    sea_col = deep * smoothstep(0.1, 1.5, ocean_depth)[..., None] + mid * (smoothstep(0.02, 0.3, ocean_depth) * (1 - smoothstep(0.1, 1.5, ocean_depth)))[..., None] \
        + shallow * (1 - smoothstep(0.02, 0.3, ocean_depth))[..., None]
    sea_col = sea_col * (0.9 + 0.2 * fbm3(X, Y, Z, 5.0, 3, seed=2.2))[..., None]
    seaice = smoothstep(72, 82, alat)[..., None] * 0.8
    sea_col = sea_col * (1 - seaice) + rgb("#dfe6ea") * seaice
    c = land_col * land[..., None] + sea_col * (1 - land[..., None])
    print(f"  colour {time.time() - t0:.1f}s")
    # ---- outputs: albedo (upsampled with fine detail), normal, ocean/lights, clouds
    os.makedirs(OUT, exist_ok=True)
    alb = Image.fromarray((np.clip(c, 0, 1) ** (1 / 1.0) * 255).astype(np.uint8)).resize((4096, 2048), Image.LANCZOS)
    a = np.asarray(alb, dtype=np.float32) / 255.0
    lon2, lat2 = lonlat_grid(4096, 2048)
    X2, Y2, Z2 = sphere_xyz(lon2, lat2)
    fine = fbm3(X2, Y2, Z2, 40.0, 3, seed=6.6)
    land2 = np.asarray(Image.fromarray((land * 255).astype(np.uint8)).resize((4096, 2048), Image.BILINEAR), dtype=np.float32) / 255.0
    a *= (0.92 + 0.16 * fine * land2)[..., None]
    Image.fromarray((np.clip(a, 0, 1) * 255).astype(np.uint8)).save(os.path.join(OUT, "earth_albedo.webp"), quality=88, method=6)
    # normal from elevation (land only)
    e = np.where(land > 0.5, elev, 0.0).astype(np.float32)
    gx = (np.roll(e, -1, 1) - np.roll(e, 1, 1)) / np.maximum(np.cos(np.radians(lat)), 0.1)
    gy = (np.roll(e, -1, 0) - np.roll(e, 1, 0))
    k = 3.5
    n = np.stack([-gx * k, gy * k, np.ones_like(gx)], -1)
    n /= np.linalg.norm(n, axis=-1, keepdims=True)
    Image.fromarray(((n * 0.5 + 0.5) * 255).astype(np.uint8)).save(os.path.join(OUT, "earth_normal.webp"), quality=90, method=6)
    # ocean mask (R) for specular, night lights (G): few, dim, clustered on habitable coasts and plains
    cities = (fbm3(X, Y, Z, 30.0, 2, seed=12.1) > 0.72) * (fbm3(X, Y, Z, 4.0, 2, seed=13.3) > 0.55) * land * (moist > 0.3) * (temp > 0.35) * (elev < 1.2)
    lights = np.asarray(Image.fromarray((cities * 255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(1.2)), dtype=np.float32) / 255.0
    spec = np.stack([(1 - land) * 255, np.clip(lights * 2.2, 0, 1) * 255, np.zeros_like(land)], -1).astype(np.uint8)
    Image.fromarray(spec).save(os.path.join(OUT, "earth_spec.webp"), quality=90, method=6)
    print(f"  albedo/normal/spec {time.time() - t0:.1f}s")
    # clouds: domain-warped fbm in latitude bands, storm spirals at mid latitudes, brown dust fronts over dry land
    wx = fbm3(X, Y, Z, 2.0, 4, seed=21.0) - 0.5
    wy = fbm3(X, Y, Z, 2.0, 4, seed=22.0) - 0.5
    cl = fbm3(X + wx * 0.8, Y + wy * 0.8, Z + (wx - wy) * 0.4, 3.2, 7, gain=0.55, seed=23.0)
    beltc = 0.5 + 0.35 * np.exp(-((alat - 4) / 8) ** 2) + 0.3 * np.exp(-((alat - 55) / 12) ** 2) - 0.25 * np.exp(-((alat - 25) / 8) ** 2)
    cov = smoothstep(0.52 - beltc * 0.12, 0.72 - beltc * 0.1, cl * (0.75 + beltc * 0.4))
    dustc = smoothstep(0.55, 0.8, fbm3(X + wy, Y + wx, Z, 2.6, 6, seed=31.0)) * smoothstep(0.45, 0.2, moist) * land * 0.75
    dustc = np.asarray(Image.fromarray((np.clip(dustc, 0, 1) * 255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(5)), dtype=np.float32) / 255.0
    alpha = np.clip(cov * 0.95 + dustc, 0, 1)
    tint = np.clip(dustc / np.maximum(alpha, 1e-3), 0, 1)
    col = np.stack([1.0 - 0.18 * tint, 1.0 - 0.3 * tint, 1.0 - 0.5 * tint], -1) * (0.85 + 0.15 * cl[..., None])
    rgba = np.concatenate([np.clip(col, 0, 1), alpha[..., None]], -1)
    Image.fromarray((rgba * 255).astype(np.uint8), "RGBA").save(os.path.join(OUT, "earth_clouds.webp"), quality=86, method=6)
    print(f"  clouds {time.time() - t0:.1f}s")


